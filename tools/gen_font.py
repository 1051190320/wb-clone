def find_sc_font(size):
    """在 ttc 里找到 SC (简体中文) face"""
    for i in range(20):
        try:
            f = ImageFont.truetype(TTC, size, index=i)
        except Exception:
            break
        name = " ".join(f.getname())
        if "SC" in name and "Mono" not in name:
            return f
    # 兜底: 任意中文 face
    return ImageFont.truetype(TTC, size, index=0)


def glyph_bits(ch, font, w, h, big=24):
    """把单个字符渲染成 w*h 二值点阵, 返回 list[bytes]
    先在大画布上居中渲染 (允许笔画出格不裁剪), 再缩放到目标尺寸"""
    img = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(img)
    d.text((big // 2, big // 2), ch, font=font, fill=255, anchor="mm")
    img = img.resize((w, h), Image.LANCZOS)
    px = img.load()
    rows = []
    for r in range(h):
        val = 0
        for c in range(w):
            if px[c, r] > 110:
                val |= (1 << (w - 1 - c))
        # 按 w 位对齐输出
        if w == 16:
            rows.append(bytes([(val >> 8) & 0xFF, val & 0xFF]))
        elif w == 8:
            rows.append(bytes([val & 0xFF]))
        else:
            raise ValueError(w)
    return rows


def main():
    # ---------- 中文 16x16 ----------
    chars = sorted(set(CN_CHARS))
    font16 = find_sc_font(20)
    lines = []
    lines.append("// Auto-generated by gen_font.py — do not edit")
    lines.append("// 中文 16x16 / ASCII 8x16 点阵字库 (Noto Sans CJK SC)")
    lines.append("#pragma once")
    lines.append("#include <Arduino.h>")
    lines.append("")
    lines.append("struct WbGlyph { uint16_t code; uint8_t bits[32]; };")
    lines.append("")
    lines.append("// 共 %d 个汉字, 按 code 升序, 固件内二分查找" % len(chars))
    lines.append("static const WbGlyph CN_FONT[] = {")
    for ch in chars:
        rows = glyph_bits(ch, font16, 16, 16)
        flat = []
        for r in rows:
            flat.append("0x%02X,0x%02X" % (r[0], r[1]))
        code = ord(ch)
        lines.append("  {0x%04X,{%s}}," % (code, ",".join(flat)))
    lines.append("};")
    lines.append("#define CN_FONT_COUNT (sizeof(CN_FONT)/sizeof(CN_FONT[0]))")
    lines.append("")
    # ---------- ASCII 8x16 ----------
    font8 = find_sc_font(16)
    lines.append("// ASCII 0x20-0x7E, 8x16")
    lines.append("static const uint8_t ASC_FONT[][16] = {")
    for code in range(0x20, 0x7F):
        ch = chr(code)
        rows = glyph_bits(ch, font8, 8, 16, big=12)
        flat = ["0x%02X" % r[0] for r in rows]
        lines.append("  {%s}, // %s" % (",".join(flat), ("'" + ch + "'").replace("\\", "\\\\").replace("'", "\\'")))
    lines.append("};")
    lines.append("#define ASC_FONT_FIRST 0x20")
    lines.append("")

    out = "/workspace/wb-clone/firmware/wb_display/cn_font.h"
    import os
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("OK: %d CJK glyphs -> %s (%d bytes)" % (len(chars), out, len("\n".join(lines))))


if __name__ == "__main__":
    main()
