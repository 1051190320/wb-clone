"""生成 ESP32 固件用的点阵字库 cn_font.h

- 中文: 16x16 点阵, 每字 32 字节 (每行 2 字节, MSB 在前)
- ASCII: 8x16 点阵, 0x20-0x7E, 每字 16 字节 (每行 1 字节)

依赖: Pillow + Noto Sans CJK SC
"""
